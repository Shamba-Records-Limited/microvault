//go:build ignore

// gen writes countries.go and subdivisions.go from a pinned iso-codes
// release. Run with: go generate ./pkg/iso3166
package main

import (
	"bytes"
	"encoding/json"
	"fmt"
	"go/format"
	"log"
	"net/http"
	"os"
	"regexp"
	"sort"
	"strings"
)

const (
	release = "v4.20.1"
	base    = "https://salsa.debian.org/iso-codes-team/iso-codes/-/raw/" + release + "/data/"
)

type entry struct {
	Alpha2     string `json:"alpha_2"`
	Code       string `json:"code"`
	Name       string `json:"name"`
	CommonName string `json:"common_name"`
	Parent     string `json:"parent"`
}

var bracketSuffix = regexp.MustCompile(`\s*\[[^\]]*\]\s*$`)

func fetch(file, key string) []entry {
	resp, err := http.Get(base + file)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("%s: %s", file, resp.Status)
	}
	var doc map[string][]entry
	if err := json.NewDecoder(resp.Body).Decode(&doc); err != nil {
		log.Fatalf("%s: %v", file, err)
	}
	return doc[key]
}

func write(path string, src *bytes.Buffer) {
	out, err := format.Source(src.Bytes())
	if err != nil {
		log.Fatalf("%s: %v", path, err)
	}
	if err := os.WriteFile(path, out, 0o644); err != nil {
		log.Fatal(err)
	}
}

func main() {
	countries := fetch("iso_3166-1.json", "3166-1")
	for i := range countries {
		if countries[i].CommonName != "" {
			countries[i].Name = countries[i].CommonName
		}
	}
	sort.Slice(countries, func(i, j int) bool { return countries[i].Name < countries[j].Name })

	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by gen.go from iso-codes %s ISO 3166-1. DO NOT EDIT.\n\npackage iso3166\n\n", release)
	b.WriteString("// Countries is every ISO 3166-1 country, sorted by English name.\nvar Countries = []Country{\n")
	for _, c := range countries {
		fmt.Fprintf(&b, "{Code: %q, Name: %q},\n", c.Alpha2, c.Name)
	}
	b.WriteString("}\n")
	write("countries.go", &b)

	byCountry := map[string][]entry{}
	for _, s := range fetch("iso_3166-2.json", "3166-2") {
		if s.Parent != "" {
			continue
		}
		s.Name = strings.TrimSpace(bracketSuffix.ReplaceAllString(s.Name, ""))
		cc, _, _ := strings.Cut(s.Code, "-")
		byCountry[cc] = append(byCountry[cc], s)
	}
	codes := make([]string, 0, len(byCountry))
	for cc := range byCountry {
		codes = append(codes, cc)
	}
	sort.Strings(codes)

	b.Reset()
	fmt.Fprintf(&b, "// Code generated by gen.go from iso-codes %s ISO 3166-2. DO NOT EDIT.\n\npackage iso3166\n\n", release)
	b.WriteString("// subdivisions holds each country's first-level ISO 3166-2 subdivisions,\n// sorted by name.\nvar subdivisions = map[string][]Subdivision{\n")
	for _, cc := range codes {
		subs := byCountry[cc]
		sort.Slice(subs, func(i, j int) bool { return subs[i].Name < subs[j].Name })
		fmt.Fprintf(&b, "%q: {\n", cc)
		for _, s := range subs {
			fmt.Fprintf(&b, "{Code: %q, Name: %q},\n", s.Code, s.Name)
		}
		b.WriteString("},\n")
	}
	b.WriteString("}\n")
	write("subdivisions.go", &b)
}
